#!/bin/sh
# Периодический reload nginx, чтобы подхватывать продлённый сертификат.
#
# nginx читает сертификат один раз при старте и держит в памяти. certbot внутри
# своего контейнера обновляет файлы, но мастер-процесс продолжает отдавать старый
# — через 90 дней прод молча ложится с протухшим сертом. Reload бесшовный:
# воркеры перезапускаются, соединения не рвутся.
#
# Живёт в /docker-entrypoint.d/, а не в `command:`. Энтрипойнт nginx прогоняет
# templates/*.template через envsubst ТОЛЬКО когда первый аргумент команды —
# `nginx`. Подменишь command на `sh -c ...` — шаблон молча не применится, и
# контейнер поднимется со стоковым конфигом образа.
#
# Скрипт обязан завершиться: энтрипойнт выполняет файлы отсюда последовательно и
# только потом запускает сам nginx. Поэтому петля уходит в фон.
# Первый sleep отрабатывает раньше, чем случится первый reload, так что мастер к
# тому моменту уже поднят.

( while :; do
    sleep 6h
    nginx -s reload 2>/dev/null || true
  done ) &
